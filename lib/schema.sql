-- Digital Board schema (PostgreSQL). Applied idempotently on first DB access.
-- Postgres has ADD COLUMN IF NOT EXISTS, so added columns live at the bottom of
-- this file instead of in a migration list in code.

CREATE TABLE IF NOT EXISTS users (
  id            TEXT PRIMARY KEY,
  email         TEXT NOT NULL UNIQUE,
  name          TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  color         TEXT NOT NULL,
  is_admin      INTEGER NOT NULL DEFAULT 0,
  created_at    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
  token      TEXT PRIMARY KEY,
  user_id    TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);

CREATE TABLE IF NOT EXISTS settings (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS projects (
  id         TEXT PRIMARY KEY,
  name       TEXT NOT NULL,
  position   INTEGER NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS columns (
  id         TEXT PRIMARY KEY,
  project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  title      TEXT NOT NULL,
  color      TEXT NOT NULL,
  position   INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS columns_project ON columns(project_id, position);

CREATE TABLE IF NOT EXISTS project_members (
  project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  user_id    TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role       TEXT NOT NULL CHECK (role IN ('admin', 'editor', 'viewer')),
  PRIMARY KEY (project_id, user_id)
);

CREATE TABLE IF NOT EXISTS tasks (
  id          TEXT PRIMARY KEY,
  column_id   TEXT NOT NULL REFERENCES columns(id) ON DELETE CASCADE,
  title       TEXT NOT NULL,
  description TEXT,
  label       TEXT,
  priority    TEXT NOT NULL DEFAULT 'medium',
  assignee_id TEXT REFERENCES users(id) ON DELETE SET NULL,
  due_date    TEXT,
  position    INTEGER NOT NULL,
  created_at  TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS tasks_column ON tasks(column_id, position);
CREATE INDEX IF NOT EXISTS tasks_assignee ON tasks(assignee_id);

-- BY DEFAULT rather than ALWAYS: bulk restores write explicit ids.
CREATE TABLE IF NOT EXISTS task_events (
  id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id  TEXT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  actor_id TEXT REFERENCES users(id) ON DELETE SET NULL,
  text     TEXT NOT NULL,
  at       TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS task_events_task ON task_events(task_id, id);

CREATE TABLE IF NOT EXISTS canvases (
  id         TEXT PRIMARY KEY,
  project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name       TEXT NOT NULL,
  position   INTEGER NOT NULL,
  snapshot   TEXT,
  updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS canvases_project ON canvases(project_id, position);

CREATE TABLE IF NOT EXISTS messages (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author_id    TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  -- NULL = the workspace channel; a user id = a direct message to that person.
  recipient_id TEXT REFERENCES users(id) ON DELETE CASCADE,
  body         TEXT NOT NULL,
  created_at   TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS messages_channel ON messages(recipient_id, id);
CREATE INDEX IF NOT EXISTS messages_dm ON messages(author_id, recipient_id, id);

-- Per-conversation read cursor. channel = 'all' for the workspace channel,
-- otherwise the other person's user id.
CREATE TABLE IF NOT EXISTS message_reads (
  user_id      TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  channel      TEXT NOT NULL,
  last_read_id INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, channel)
);

CREATE TABLE IF NOT EXISTS attachments (
  id         TEXT PRIMARY KEY,
  message_id INTEGER NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
  name       TEXT NOT NULL,
  mime       TEXT NOT NULL,
  size       INTEGER NOT NULL,
  data       BYTEA NOT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS attachments_message ON attachments(message_id);

CREATE TABLE IF NOT EXISTS activity_reads (
  user_id  TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  event_id INTEGER NOT NULL REFERENCES task_events(id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, event_id)
);

-- Columns added after the first release. Append only.
ALTER TABLE users    ADD COLUMN IF NOT EXISTS last_seen_at TEXT;
ALTER TABLE messages ADD COLUMN IF NOT EXISTS edited_at    TEXT;
ALTER TABLE tasks    ADD COLUMN IF NOT EXISTS description  TEXT;
ALTER TABLE attachments ADD COLUMN IF NOT EXISTS data BYTEA;
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_activity_read_id INTEGER NOT NULL DEFAULT 0;

-- ── Multi-workspace ─────────────────────────────────────────────────────────
-- Tenancy is carried by three columns. Everything under a project (columns,
-- tasks, task_events, canvases) reaches its workspace through projects, and
-- attachments / message_reads reach it through messages and users, so those
-- tables need no column of their own.
CREATE TABLE IF NOT EXISTS workspaces (
  id         TEXT PRIMARY KEY,
  name       TEXT NOT NULL,
  created_at TEXT NOT NULL
);

ALTER TABLE users    ADD COLUMN IF NOT EXISTS workspace_id TEXT REFERENCES workspaces(id) ON DELETE CASCADE;
ALTER TABLE projects ADD COLUMN IF NOT EXISTS workspace_id TEXT REFERENCES workspaces(id) ON DELETE CASCADE;
ALTER TABLE messages ADD COLUMN IF NOT EXISTS workspace_id TEXT REFERENCES workspaces(id) ON DELETE CASCADE;

-- Backfill for an install that predates workspaces: everything it holds is, by
-- definition, one workspace. Named from the old settings row. Runs once —
-- the guard is "some row still has no workspace_id".
INSERT INTO workspaces (id, name, created_at)
SELECT 'ws-legacy', COALESCE((SELECT value FROM settings WHERE key = 'workspace'), 'Workspace'), now()::text
 WHERE EXISTS (SELECT 1 FROM users WHERE workspace_id IS NULL)
   AND NOT EXISTS (SELECT 1 FROM workspaces WHERE id = 'ws-legacy');

UPDATE users    SET workspace_id = 'ws-legacy' WHERE workspace_id IS NULL;
UPDATE projects SET workspace_id = 'ws-legacy' WHERE workspace_id IS NULL;
UPDATE messages SET workspace_id = 'ws-legacy' WHERE workspace_id IS NULL;

CREATE INDEX IF NOT EXISTS users_workspace    ON users(workspace_id);
CREATE INDEX IF NOT EXISTS projects_workspace ON projects(workspace_id, position);
CREATE INDEX IF NOT EXISTS messages_workspace ON messages(workspace_id, recipient_id, id);

-- Email stays globally unique on purpose. One address is one account in one
-- workspace, which keeps sign-in a single lookup with no "which workspace?"
-- step. Registering with an address that already exists is refused.

-- AI agent provider for the canvas, as JSON ({provider, model, baseUrl, apiKey}).
-- Set by a workspace admin in Settings; NULL means the agent is off.
ALTER TABLE workspaces ADD COLUMN IF NOT EXISTS ai_config TEXT;

-- Canvas AI agent conversations, one row per chat, shared by the sheet's editors.
-- `messages` is a JSON array of {role, content, shown?, drew?}; turns are appended
-- with `||` so two people chatting in one room can't overwrite each other.
CREATE TABLE IF NOT EXISTS agent_chats (
  id         TEXT PRIMARY KEY,
  canvas_id  TEXT NOT NULL REFERENCES canvases(id) ON DELETE CASCADE,
  author_id  TEXT REFERENCES users(id) ON DELETE SET NULL,
  title      TEXT NOT NULL,
  messages   JSONB NOT NULL DEFAULT '[]',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS agent_chats_canvas ON agent_chats(canvas_id, updated_at);

-- Per-project GitHub link: JSON {repo, token}; see lib/github.ts.
ALTER TABLE projects ADD COLUMN IF NOT EXISTS github TEXT;

-- Task keys (WEB-42): a short key per project and a number per task, so branches,
-- PRs and commits can name a card. Backfills only touch rows still missing a value.
ALTER TABLE projects ADD COLUMN IF NOT EXISTS key TEXT;
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS number INTEGER;
UPDATE projects SET key = COALESCE(NULLIF(upper(left(regexp_replace(name, '[^A-Za-z]', '', 'g'), 3)), ''), 'TASK')
 WHERE key IS NULL;
UPDATE tasks t SET number = x.n
  FROM (SELECT t2.id,
               ROW_NUMBER() OVER (PARTITION BY c.project_id ORDER BY t2.created_at, t2.id)
               + (SELECT COALESCE(MAX(t3.number), 0) FROM tasks t3 JOIN columns c3 ON c3.id = t3.column_id
                   WHERE c3.project_id = c.project_id) AS n
          FROM tasks t2 JOIN columns c ON c.id = t2.column_id
         WHERE t2.number IS NULL) x
 WHERE t.id = x.id;

-- GitHub items a webhook tied to a task (by its key), kept past the GitHub view's
-- recent-activity window. kind matches lib/github.ts: pulls | commits | branches.
CREATE TABLE IF NOT EXISTS task_links (
  task_id    TEXT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  kind       TEXT NOT NULL CHECK (kind IN ('pulls', 'commits', 'branches')),
  ext_id     TEXT NOT NULL,
  title      TEXT NOT NULL,
  url        TEXT NOT NULL,
  ref        TEXT NOT NULL,
  state      TEXT,
  author     TEXT,
  sha        TEXT,
  ci         TEXT,
  at         TEXT,
  PRIMARY KEY (task_id, kind, ext_id)
);

-- Generic inbound webhook (Zapier, Make, forms): sha256 hex of the project's bearer
-- token. Only the hash is stored, so the token is shown once when it is made.
ALTER TABLE projects ADD COLUMN IF NOT EXISTS inbound_token TEXT;

-- iCal feed (GET /api/integrations/ical): a read-only link calendar apps subscribe to.
-- Stored as-is because members copy the link again later; resetting it revokes old links.
ALTER TABLE projects ADD COLUMN IF NOT EXISTS ical_token TEXT;

-- Outgoing webhook: JSON {url, secret, events[], last{status, event, at}}; see lib/outgoing.ts.
-- The secret signs each delivery and never leaves the server after it is first shown.
ALTER TABLE projects ADD COLUMN IF NOT EXISTS outgoing JSONB;

-- Card comments are task_events with kind 'comment', so they share the history,
-- Inbox and bell feeds. Every other event keeps the default.
ALTER TABLE task_events ADD COLUMN IF NOT EXISTS kind TEXT NOT NULL DEFAULT 'event';
-- Card comments written by the AI agent (called with "@agent"); actor_id is who called it.
ALTER TABLE task_events ADD COLUMN IF NOT EXISTS agent BOOLEAN NOT NULL DEFAULT false;

-- Checklist: JSON array of {text, done}, saved whole on every change.
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS checklist JSONB NOT NULL DEFAULT '[]';

-- Archived cards stay in their column but leave the board, feeds and counts.
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS archived_at TEXT;

-- Repeat rule: NULL, 'daily', 'weekly' or 'monthly'. Moving the card into the
-- project's last column creates the next one (see moveTask).
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS repeat TEXT;

-- Several assignees per card. Labels stay one text column, comma-separated.
-- tasks.assignee_id is retired: the backfill copies it here once and clears it.
CREATE TABLE IF NOT EXISTS task_assignees (
  task_id TEXT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (task_id, user_id)
);
CREATE INDEX IF NOT EXISTS task_assignees_user ON task_assignees(user_id);
INSERT INTO task_assignees (task_id, user_id)
SELECT id, assignee_id FROM tasks WHERE assignee_id IS NOT NULL ON CONFLICT DO NOTHING;
UPDATE tasks SET assignee_id = NULL WHERE assignee_id IS NOT NULL;

-- The column that means "done" (Completed counts, repeating cards, due reminders).
-- NULL falls back to the project's last column.
ALTER TABLE projects ADD COLUMN IF NOT EXISTS done_column_id TEXT REFERENCES columns(id) ON DELETE SET NULL;

-- Chat messages written by the AI agent (called with "@agent" or in a member's private
-- agent thread, a DM to themselves). author_id is the member who called it.
ALTER TABLE messages ADD COLUMN IF NOT EXISTS agent BOOLEAN NOT NULL DEFAULT false;

-- Meetings: a workspace-level schedule, separate from cards. `start_date` + `start_time`
-- are wall-clock (each viewer's browser reads them in its own time zone); `repeat` is
-- 'none', 'daily', 'weekdays', 'weekly' or 'monthly'. Attendees get a reminder
-- `remind_min` minutes before each occurrence (derived in the browser, nothing stored).
CREATE TABLE IF NOT EXISTS meetings (
  id           TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  title        TEXT NOT NULL,
  notes        TEXT,
  link         TEXT,
  start_date   TEXT NOT NULL,
  start_time   TEXT NOT NULL,
  duration_min INTEGER NOT NULL DEFAULT 30,
  repeat       TEXT NOT NULL DEFAULT 'none',
  remind_min   INTEGER NOT NULL DEFAULT 15,
  created_by   TEXT REFERENCES users(id) ON DELETE SET NULL,
  created_at   TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS meetings_workspace ON meetings(workspace_id);
CREATE TABLE IF NOT EXISTS meeting_attendees (
  meeting_id TEXT NOT NULL REFERENCES meetings(id) ON DELETE CASCADE,
  user_id    TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (meeting_id, user_id)
);

-- Images added inside a card; the first one is the card's cover on the board.
-- Bytes live here, not in tasks, so board queries never drag them along.
CREATE TABLE IF NOT EXISTS task_images (
  id         TEXT PRIMARY KEY,
  task_id    TEXT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  name       TEXT NOT NULL,
  mime       TEXT NOT NULL,
  data       BYTEA NOT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS task_images_task ON task_images(task_id, created_at);

-- Emailed password-reset links (only when SMTP_URL + APP_URL are set). The token
-- itself is only in the email; this keeps its sha256, valid for an hour.
CREATE TABLE IF NOT EXISTS password_resets (
  token_hash TEXT PRIMARY KEY,
  user_id    TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS password_resets_user ON password_resets(user_id);
