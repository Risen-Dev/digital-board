const Excalidraw = dynamic(
  () =>
    import("@excalidraw/excalidraw").then(
      (module) => module.Excalidraw,
    ),
  {
    ssr: false,

    loading: () => (
      <div className="flex h-full items-center justify-center text-sm text-muted-foreground">
        Loading canvas…
      </div>
    ),
  },
);

class CanvasBoundary extends Component<
  {
    children: ReactNode;
  },
  {
    failed: boolean;
  }
> {
  state = {
    failed: false,
  };

  static getDerivedStateFromError() {
    return {
      failed: true,
    };
  }

  render() {
    if (!this.state.failed) {
      return this.props.children;
    }

    return (
      <div className="flex h-full flex-col items-center justify-center gap-3 p-10 text-center">
        <p className="text-sm font-medium">
          The canvas could not load
        </p>

        <p className="max-w-sm text-xs text-muted-foreground">
          This usually means the app was updated while this tab
          was open. Your drawing is safe — reload to pick up the
          new version.
        </p>

        <button
          type="button"
          onClick={() => window.location.reload()}
          className="rounded-md bg-primary px-3 py-1.5 text-xs font-medium text-primary-foreground transition-opacity hover:opacity-90"
        >
          Reload
        </button>
      </div>
    );
  }
}

// Half of Excalidraw's limit, leaving room for the flow itself.
const NEAR = 500_000;

/**
 * Draws an agent flow to the right of whatever is on the sheet. It goes in as
 * a normal scene edit, so it saves, syncs to peers and undoes like a stroke.
 */
async function drawFlow(api: ExcalidrawImperativeAPI, flow: Flow, by: string) {
  const { convertToExcalidrawElements, CaptureUpdateAction } = await import("@excalidraw/excalidraw");

  const all = api.getSceneElementsIncludingDeleted();
  // Excalidraw rejects new elements beyond ±1e6. A stray element far off on the
  // sheet would push the flow out there, so only nearby ones decide the spot.
  const near = (v: number) => Math.abs(v) < NEAR;
  const placed = all.filter((e) => !e.isDeleted && near(e.x) && near(e.y) && near(e.x + e.width));
  const origin = placed.length
    ? { x: Math.max(...placed.map((e) => e.x + e.width)) + 160, y: Math.min(...placed.map((e) => e.y)) }
    : { x: 0, y: 0 };

  const added = convertToExcalidrawElements(
    layoutFlow(flow, origin, `${crypto.randomUUID().slice(0, 8)}-`, `Generated by ${by}`) as ExcalidrawElementSkeleton[],
  );
  api.updateScene({ elements: [...all, ...added], captureUpdate: CaptureUpdateAction.IMMEDIATELY });
  api.scrollToContent(added, { fitToContent: true, animate: true });
  return added.length;
}

/** What a typed tag becomes: the `@tag` form cards and chat mention it by. */
const tagName = (raw: string) => raw.trim().replace(/[^\w-]+/g, "-").replace(/^-+|-+$/g, "");

type SceneChange = Parameters<NonNullable<ExcalidrawProps["onChange"]>>;
type Box = { tag: string; left: number; top: number; width: number; height: number };

/**
 * A dashed frame and an @name label around each tagged group, drawn over the canvas
 * in screen space. Fed straight from onChange so scrolling re-renders only this.
 * ponytail: unrotated bounds; rotated shapes get a slightly off frame.
 */
function TagHighlights({ feedRef }: { feedRef: { current: ((...change: SceneChange) => void) | null } }) {
  const [boxes, setBoxes] = useState<Box[]>([]);
  useEffect(() => {
    let last = "";
    feedRef.current = (elements, appState) => {
      const bounds = new Map<string, [number, number, number, number]>();
      for (const e of elements) {
        const tag = e.customData?.tag;
        if (!tag || e.isDeleted) continue;
        const xs = "points" in e ? e.points.map(([x]) => e.x + x) : [e.x, e.x + e.width];
        const ys = "points" in e ? e.points.map(([, y]) => e.y + y) : [e.y, e.y + e.height];
        const b = bounds.get(tag) ?? [Infinity, Infinity, -Infinity, -Infinity];
        bounds.set(tag, [Math.min(b[0], ...xs), Math.min(b[1], ...ys), Math.max(b[2], ...xs), Math.max(b[3], ...ys)]);
      }
      const { scrollX, scrollY, zoom } = appState;
      const pad = 12;
      const next = [...bounds].map(([tag, [x1, y1, x2, y2]]) => ({
        tag,
        left: (x1 + scrollX) * zoom.value - pad,
        top: (y1 + scrollY) * zoom.value - pad,
        width: (x2 - x1) * zoom.value + pad * 2,
        height: (y2 - y1) * zoom.value + pad * 2,
      }));
      const key = JSON.stringify(next);
      if (key !== last) {
        last = key;
        setBoxes(next);
      }
    };
    return () => { feedRef.current = null; };
  }, [feedRef]);

  return (
    // Above the drawing, below Excalidraw's toolbars (z-index 4); clicks pass through.
    <div className="pointer-events-none absolute inset-0 z-[3] overflow-hidden">
      {boxes.map((b) => (
        <div
          key={b.tag}
          className="absolute rounded-lg border-2 border-dashed border-[var(--chart-1)] bg-[var(--chart-1)]/5"
          style={{ left: b.left, top: b.top, width: b.width, height: b.height }}
        >
          <span className="absolute -top-2.5 left-2 rounded bg-[var(--chart-1)] px-1.5 py-0.5 text-[10px] font-medium leading-none text-white">
            @{b.tag}
          </span>
        </div>
      ))}
    </div>
  );
}

// The theme toggle only flips the <html> class; the `dark` prop (from the cookie)
// is stale until the next request, so follow the class live.
function subscribeTheme(onChange: () => void) {
  const observer = new MutationObserver(onChange);
  observer.observe(document.documentElement, { attributes: true, attributeFilter: ["class"] });
  return () => observer.disconnect();
}

type CanvasViewProps = {
  projectId: string;
  sheets: CanvasMeta[];
  dark: boolean;
  readOnly: boolean;
  aiEnabled: boolean;
  onChanged: () => void;
  /** An @tag clicked in a card or chat: open its sheet and select its shapes. */
  focus?: { sheetId: string; tag: string } | null;
};

export function CanvasView({
  projectId,
  sheets,
  dark,
  readOnly,
  aiEnabled,
  onChanged,
  focus,
}: CanvasViewProps) {
  const [agentOpen, setAgentOpen] = useState(false);
  const isDark = useSyncExternalStore(
    subscribeTheme,
    () => document.documentElement.classList.contains("dark"),
    () => dark,
  );

  const [selected, setSelected] = useState<
    string | null
  >(focus?.sheetId ?? null);

  const [renaming, setRenaming] = useState<
    string | null
  >(null);

  /**
   * If the selected sheet gets deleted, automatically fall back
   * to the first available sheet.
   */
  const activeId =
    selected &&
    sheets.some((sheet) => sheet.id === selected)
      ? selected
      : (sheets[0]?.id ?? null);

  /**
   * Excalidraw accepts Promise-based initialData.
   *
   * Changing activeId changes the CanvasBoundary key below,
   * causing Excalidraw to remount with the new sheet snapshot.
   */
  const initialData = useMemo(() => {
    if (!activeId) {
      return null;
    }

    return loadCanvasSnapshot(activeId)
      .then((saved) => {
        if (!saved) {
          return null;
        }

        return {
          ...saved,
          scrollToContent: true,
        };
      })
      .catch((error) => {
        console.error(
          "Failed to load canvas snapshot:",
          error,
        );

        return null;
      });
  }, [activeId]);

  const {
    status,
    onChange,
    markRemote,
    flush,
    reset,
    cancel,
  } = useCanvasPersistence(activeId, initialData);

  /**
   * Tagged with its sheet so the outgoing instance's API is never used for the
   * incoming sheet during the remount.
   */
  const [excalidraw, setExcalidraw] = useState<{
    sheetId: string;
    api: ExcalidrawImperativeAPI;
  } | null>(null);

  const live = useCanvasLive(
    activeId,
    excalidraw?.sheetId === activeId ? excalidraw.api : null,
    initialData,
    markRemote,
    () => {
      // Its row is gone: drop pending saves and let the sheet list refresh.
      cancel();
      onChanged();
    },
  );

  /**
   * Agent flows land through the session store: register this sheet's drawer only
   * after its initialData has loaded (like the live stream), or the loaded scene
   * would replace what was just drawn. Flows that arrived while the sheet was
   * closed are drawn now.
   */
  const api = excalidraw?.sheetId === activeId ? excalidraw.api : null;
  useEffect(() => {
    if (!api || !activeId || readOnly) return;
    let unregister = () => {};
    let cancelled = false;
    void Promise.resolve(initialData).then((saved) => {
      if (cancelled) return;
      unregister = registerDrawer(activeId, (flow, by) => drawFlow(api, flow, by));
      // A template's example sheet arrives as a bare flow. The server hands it to one
      // tab only (claimCanvasSeed); that tab draws it and the rest get it over live sync.
      // ponytail: if the winning tab closes before its first save, the example is lost.
      if ((saved as { seed?: unknown } | null)?.seed) {
        void claimCanvasSeed(activeId).then((seed) => {
          const flow = seed && parseFlow(seed.flow);
          if (flow && !cancelled) void drawFlow(api, flow, seed.by);
        });
      }
    });
    return () => { cancelled = true; unregister(); };
  }, [api, activeId, initialData, readOnly]);

  const highlight = useRef<((...change: SceneChange) => void) | null>(null);

  // Once per focus request, after the sheet's scene has loaded (and scrolled to content).
  const focused = useRef<typeof focus>(null);
  useEffect(() => {
    if (!api || !focus || focus.sheetId !== activeId || focused.current === focus) return;
    focused.current = focus;
    void Promise.resolve(initialData).then(() => requestAnimationFrame(() => {
      const shapes = api.getSceneElements().filter((e) => e.customData?.tag === focus.tag);
      if (!shapes.length) return;
      const group = shapes[0].groupIds.at(-1);
      api.updateScene({
        appState: {
          selectedElementIds: Object.fromEntries(shapes.map((e) => [e.id, true as const])),
          selectedGroupIds: group ? { [group]: true } : {},
        },
      });
      api.scrollToContent(shapes, { fitToContent: true, animate: true });
    }));
  }, [api, activeId, initialData, focus]);

  async function tagSelection() {
    if (!api) return;
    const ids = api.getAppState().selectedElementIds;
    // A shape's label is a separate text element that selection doesn't list.
    const chosen = (e: { id: string; containerId?: string | null }) => ids[e.id] || (!!e.containerId && ids[e.containerId]);
    const picked = api.getSceneElements().filter(chosen);
    if (!picked.length) return window.alert("Select the shapes to tag first.");
    const raw = window.prompt(
      "Name the selected shapes. They become one group that cards and chat can mention as @name. Leave blank to remove the name.",
      picked[0].customData?.tag ?? "",
    );
    if (raw === null) return;
    const tag = tagName(raw);
    // Group them like Ctrl+G, unless they already are one group.
    const outer = picked[0].groupIds.at(-1);
    const group = outer && picked.every((e) => e.groupIds.at(-1) === outer) ? null : crypto.randomUUID();
    const { newElementWith, CaptureUpdateAction } = await import("@excalidraw/excalidraw");
    api.updateScene({
      elements: api.getSceneElementsIncludingDeleted().map((e) =>
        !e.isDeleted && chosen(e)
          ? newElementWith(e, {
              // An undefined tag drops out when the scene is saved as JSON.
              customData: { ...e.customData, tag: tag || undefined },
              ...(tag && group ? { groupIds: [...e.groupIds, group] } : {}),
            })
          : e,
      ),
      captureUpdate: CaptureUpdateAction.IMMEDIATELY,
    });
    // Save now and refetch the sheet list, so cards can mention the tag straight away.
    await new Promise(requestAnimationFrame);
    await flush();
    onChanged();
  }

  async function addSheet() {
    /**
     * Make sure current sheet is persisted before changing the
     * project structure.
     */
    await flush();

    await createCanvas(
      projectId,
      `Sheet ${sheets.length + 1}`,
    );

    onChanged();
  }

  async function switchTo(id: string) {
    if (id === activeId) {
      return;
    }

    /**
     * CRITICAL:
     *
     * Wait for Sheet A to finish saving before Sheet B mounts.
     */
    await flush();

    /**
     * Remove the old in-memory scene so it can't accidentally
     * be saved again after the new sheet mounts.
     */
    reset();

    setSelected(id);
  }

  async function removeSheet(
    id: string,
    name: string,
  ) {
    const confirmed = window.confirm(
      `Delete sheet "${name}"? Its drawing goes with it.`,
    );

    if (!confirmed) {
      return;
    }

    /**
     * If deleting the active sheet, don't let a pending debounce
     * resurrect/save it after deletion.
     */
    if (id === activeId) {
      cancel();
    }

    await deleteCanvas(id);

    if (selected === id) {
      setSelected(null);
    }

    onChanged();
  }

  return (
    <div className="flex flex-1 flex-col overflow-hidden">
      {/* Sheet tabs */}
      <div className="flex shrink-0 items-center gap-1 overflow-x-auto border-b px-3 py-1.5">
        {sheets.map((sheet) => {
          const active =
            sheet.id === activeId;

          return (
            <div
              key={sheet.id}
              className={[
                "group flex shrink-0 items-center gap-1.5 rounded-md border px-2.5 py-1 text-xs transition-colors",

                active
                  ? "border-primary bg-secondary font-medium"
                  : "border-transparent text-muted-foreground hover:bg-secondary",
              ].join(" ")}
            >
              {renaming === sheet.id ? (
                <form
                  action={async (formData) => {
                    const name = String(
                      formData.get("name") ?? "",
                    ).trim();

                    if (name) {
                      await renameCanvas(
                        sheet.id,
                        name,
                      );
                    }

                    setRenaming(null);

                    onChanged();
                  }}
                  className="flex items-center gap-1"
                >
                  <input
                    name="name"
                    defaultValue={sheet.name}
                    autoFocus
                    className="w-24 rounded border bg-background px-1 py-0.5 text-xs outline-none"
                  />

                  <button
                    type="submit"
                    title="Save name"
                    className="text-muted-foreground hover:text-foreground"
                  >
                    <Check className="size-3" />
                  </button>
                </form>
              ) : (
                <>
                  <button
                    type="button"
                    onClick={() => {
                      void switchTo(sheet.id);
                    }}
                    className="max-w-32 truncate"
                  >
                    {sheet.name}
                  </button>

                  {active && !readOnly && (
                    <>
                      <button
                        type="button"
                        onClick={() =>
                          setRenaming(sheet.id)
                        }
                        title="Rename"
                        className="text-muted-foreground hover:text-foreground"
                      >
                        <Pencil className="size-3" />
                      </button>

                      <button
                        type="button"
                        onClick={() => {
                          void removeSheet(
                            sheet.id,
                            sheet.name,
                          );
                        }}
                        title="Delete sheet"
                        className="text-muted-foreground hover:text-[var(--chart-7)]"
                      >
                        <Trash2 className="size-3" />
                      </button>
                    </>
                  )}
                </>
              )}
            </div>
          );
        })}

        {!readOnly && <button
          type="button"
          onClick={() => {
            void addSheet();
          }}
          className="flex shrink-0 items-center gap-1 rounded-md px-2 py-1 text-xs text-muted-foreground transition-colors hover:bg-secondary hover:text-foreground"
        >
          <Plus className="size-3" />

          Sheet
        </button>}

        {!readOnly && activeId && (
          <button
            type="button"
            onClick={() => void tagSelection()}
            title="Group and name the selected shapes so cards and chat can mention them as @name"
            className="ml-auto flex shrink-0 items-center gap-1 rounded-md px-2 py-1 text-xs text-muted-foreground transition-colors hover:bg-secondary hover:text-foreground"
          >
            <Tag className="size-3" />
            Tag
          </button>
        )}

        {!readOnly && activeId && (
          <button
            type="button"
            onClick={() => setAgentOpen((open) => !open)}
            className={[
              "flex shrink-0 items-center gap-1 rounded-md px-2 py-1 text-xs transition-colors",
              agentOpen ? "bg-secondary text-foreground" : "text-muted-foreground hover:bg-secondary hover:text-foreground",
            ].join(" ")}
          >
            <Sparkles className="size-3" />
            Agent
          </button>
        )}

        <span className={`${!readOnly && activeId ? "" : "ml-auto "}shrink-0 pl-3 text-[11px] text-muted-foreground`}>
          {status === "saving" ? (
            "Saving…"
          ) : status === "error" ? (
            <span className="text-[var(--chart-7)]">
              Save failed — retrying on next change
            </span>
          ) : readOnly && activeId ? (
            "View only"
          ) : activeId ? (
            "Saved"
          ) : null}
        </span>
      </div>

      {/* Canvas */}
      <div className="relative flex-1">
        {activeId ? (
          /**
           * key={activeId} forces a fresh Excalidraw instance
           * whenever the selected sheet changes.
           */
          <CanvasBoundary key={activeId}>
            <Excalidraw
              initialData={initialData}
              excalidrawAPI={(api) =>
                setExcalidraw({ sheetId: activeId, api })
              }
              onChange={(elements, appState, files) => {
                onChange(elements, appState, files);
                live.onChange();
                highlight.current?.(elements, appState, files);
              }}
              onPointerUpdate={live.onPointerUpdate}
              theme={isDark ? "dark" : "light"}
              viewModeEnabled={readOnly}
            />
            <TagHighlights feedRef={highlight} />
          </CanvasBoundary>
        ) : (
          <div className="flex h-full flex-col items-center justify-center gap-3 text-center">
            <p className="text-sm text-muted-foreground">
              No sheets in this project yet.
            </p>

            {!readOnly && <button
              type="button"
              onClick={() => {
                void addSheet();
              }}
              className="flex items-center gap-1.5 rounded-md bg-primary px-3 py-1.5 text-xs font-medium text-primary-foreground"
            >
              <Plus className="size-3" />

              Create the first sheet
            </button>}
          </div>
        )}

        {activeId && agentOpen && !readOnly && (
          <CanvasAgent
            key={`agent-${activeId}`}
            canvasId={activeId}
            enabled={aiEnabled}
            onClose={() => setAgentOpen(false)}
          />
        )}
      </div>
    </div>
  );
}
